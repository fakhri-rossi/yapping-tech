export function getDefaultGreetingForTemplate(key?: string): string {
  if (!key) return '';
  if (DEFAULT_TEMPLATE_GREETINGS[key]) {
    return DEFAULT_TEMPLATE_GREETINGS[key];
  }
  const foundInDemo = Object.values(DEMO_DATA).find(
    (d) => d.id.toLowerCase() === key.toLowerCase() || d.title.toLowerCase() === key.toLowerCase()
  );
  if (foundInDemo && foundInDemo.greetingText) {
    return foundInDemo.greetingText;
  }
  return DEFAULT_TEMPLATE_GREETINGS['romantic-neon-poetry'];
}
